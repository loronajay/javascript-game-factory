import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { CANON_BOWLERS } = require("../animation-core.js");

const toolDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.dirname(toolDirectory);
const DEFAULT_BIOS_DIRECTORY = path.join(projectRoot, "assets", "characters", "character-bios");
const DEFAULT_OUTPUT_PATH = path.join(projectRoot, "character-catalog-data.js");

const FIELD_BY_LABEL = Object.freeze({
  Age: "age",
  Hometown: "hometown",
  Occupation: "occupation",
  "Bowling Style": "bowlingStyle",
  "Favorite Ball": "favoriteBall",
  Personality: "personality",
  Bio: "bio",
});

export const REQUIRED_BIO_FIELDS = Object.freeze(Object.values(FIELD_BY_LABEL));

function normalizeSectionValue(lines) {
  while (lines[0]?.trim() === "") lines.shift();
  while (lines.at(-1)?.trim() === "") lines.pop();
  return lines.join("\n").trim();
}

export function parseCharacterBio(markdown, slug) {
  const normalizedSlug = String(slug || "").trim();
  if (!normalizedSlug) throw new Error("Character biography requires a slug.");
  const lines = String(markdown || "").replace(/\r\n?/g, "\n").split("\n");
  const heading = lines.shift()?.match(/^#\s+(.+?)\s*$/);
  if (!heading) throw new Error(`${normalizedSlug} biography requires a level-one name heading.`);

  const values = {};
  let currentField = "";
  let currentLines = [];
  const commitSection = () => {
    if (!currentField) return;
    if (Object.hasOwn(values, currentField)) throw new Error(`${normalizedSlug} repeats ${currentField}.`);
    values[currentField] = normalizeSectionValue(currentLines);
    currentLines = [];
  };

  for (const line of lines) {
    const labelMatch = line.match(/^\*\*(.+?)\*\*\s*$/);
    if (labelMatch) {
      commitSection();
      currentField = FIELD_BY_LABEL[labelMatch[1]];
      if (!currentField) throw new Error(`${normalizedSlug} has unknown biography field ${labelMatch[1]}.`);
      continue;
    }
    if (currentField) currentLines.push(line);
  }
  commitSection();

  for (const field of REQUIRED_BIO_FIELDS) {
    if (!values[field]) throw new Error(`${normalizedSlug} biography is missing ${field}.`);
  }

  return {
    slug: normalizedSlug,
    name: heading[1].trim(),
    ...Object.fromEntries(REQUIRED_BIO_FIELDS.map((field) => [field, values[field]])),
  };
}

export function buildCharacterCatalog({
  biosDirectory = DEFAULT_BIOS_DIRECTORY,
  roster = CANON_BOWLERS,
} = {}) {
  const files = fs.readdirSync(biosDirectory)
    .filter((file) => file.toLowerCase().endsWith(".md") && file.toLowerCase() !== "readme.md")
    .sort();
  const rosterBySlug = new Map(roster.map((bowler) => [bowler.slug, bowler]));
  const fileBySlug = new Map(files.map((file) => [path.basename(file, ".md"), file]));
  const unknownSlugs = [...fileBySlug.keys()].filter((slug) => !rosterBySlug.has(slug));
  if (unknownSlugs.length) throw new Error(`Unknown biography files: ${unknownSlugs.join(", ")}`);

  const missingSlugs = [...rosterBySlug.keys()].filter((slug) => !fileBySlug.has(slug));
  if (missingSlugs.length) throw new Error(`Missing biography files: ${missingSlugs.join(", ")}`);

  return roster.map((bowler) => {
    const file = fileBySlug.get(bowler.slug);
    const entry = parseCharacterBio(fs.readFileSync(path.join(biosDirectory, file), "utf8"), bowler.slug);
    if (entry.name !== bowler.name) {
      throw new Error(`${bowler.slug} heading must be ${bowler.name}, received ${entry.name}.`);
    }
    return entry;
  });
}

export function renderCharacterCatalogModule(catalog) {
  const json = JSON.stringify(catalog, null, 2);
  return `/* Generated by tools/build-character-catalog.mjs. Do not edit by hand. */
(function publishCharacterCatalog(root) {
  "use strict";
  const entries = ${json};
  const catalog = Object.freeze(entries.map((entry) => Object.freeze(entry)));
  if (typeof module === "object" && module.exports) module.exports = catalog;
  root.YamCharacterCatalogData = catalog;
})(typeof globalThis !== "undefined" ? globalThis : this);
`;
}

export function writeCharacterCatalog({
  biosDirectory = DEFAULT_BIOS_DIRECTORY,
  outputPath = DEFAULT_OUTPUT_PATH,
  roster = CANON_BOWLERS,
} = {}) {
  const catalog = buildCharacterCatalog({ biosDirectory, roster });
  fs.writeFileSync(outputPath, renderCharacterCatalogModule(catalog), "utf8");
  return catalog;
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) {
  const catalog = writeCharacterCatalog();
  console.log(`Wrote ${catalog.length} character biographies to ${path.relative(projectRoot, DEFAULT_OUTPUT_PATH)}.`);
}
