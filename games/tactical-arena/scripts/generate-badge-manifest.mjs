// Generates the client's player-badge art manifest from the files on disk, the same way
// generate-skin-manifest.mjs does for skins: scan the asset folder, prefer the runtime
// WebP over the authored PNG source, and write a generated module the UI imports.
//
// Art ids are filename stems (blood-moon.webp -> "blood-moon"). The server badge catalog
// names the art it wants by that id; tests/player-badges.test.js fails if a catalog badge
// has no art here, which is what keeps "added a badge" from shipping as a broken image.
//
// Workflow: drop <art-id>.png in assets/player-badges/, run `npm run badges:art` to make
// the WebP, then `npm run badges` (or just `npm test`, which runs it) to refresh this.

import { readdir, writeFile } from "node:fs/promises";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BADGE_ROOT = join(ROOT, "assets", "player-badges");
const OUT_FILE = join(ROOT, "src", "ui", "badgeManifest.generated.js");
const BADGE_ASSET_EXTENSIONS = new Set([".png", ".webp"]);
// The WebP is the runtime asset; the PNG beside it is the authored source and is only
// used when a badge has not been converted yet.
const EXTENSION_PRIORITY = Object.freeze({ ".webp": 0, ".png": 1 });

const entriesById = new Map();
let files = [];
try {
  files = await readdir(BADGE_ROOT);
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}

for (const file of files) {
  const extension = extname(file).toLowerCase();
  if (!BADGE_ASSET_EXTENSIONS.has(extension)) continue;
  const id = file.slice(0, -extension.length);
  const existing = entriesById.get(id);
  const priority = EXTENSION_PRIORITY[extension] ?? 99;
  if (existing && (EXTENSION_PRIORITY[extname(existing.file).toLowerCase()] ?? 99) <= priority) continue;
  entriesById.set(id, { id, file });
}

const entries = [...entriesById.values()].sort((left, right) => left.id.localeCompare(right.id));

const body = `// Generated by scripts/generate-badge-manifest.mjs. Do not edit by hand.
// Add PNG art to assets/player-badges/, run \`npm run badges:art\`, then rerun the generator.
export const BADGE_ART_MANIFEST = Object.freeze(${JSON.stringify(entries, null, 2)
  .replace(/"([^"]+)":/g, "$1:")});
`;

await writeFile(OUT_FILE, body, "utf8");
console.log(`Wrote ${relative(ROOT, OUT_FILE)} with ${entries.length} badges.`);
